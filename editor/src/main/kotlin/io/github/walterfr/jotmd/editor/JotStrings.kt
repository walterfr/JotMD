fun stringsFor(language: AppLanguage, locale: Locale = Locale.getDefault()): JotStrings = when (language) {
    AppLanguage.PT_BR -> PtBrStrings
    AppLanguage.EN -> EnStrings
    AppLanguage.SYSTEM -> if (locale.language.lowercase().startsWith("pt")) PtBrStrings else EnStrings
}

val LocalJotStrings = staticCompositionLocalOf { PtBrStrings }
